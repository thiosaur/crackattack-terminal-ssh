#!/bin/sh
# Writes compose.coolify.yml on stdout, from compose.yml.
#
# Coolify refuses a variable (${...}) in the source of a volume, and compose.yml has one for the
# file of keys. The Coolify version has the host's file written out: /root/.ssh/authorized_keys.
#
#   tools/coolify-compose.sh > compose.coolify.yml
set -eu

ROOT=$(cd "$(dirname "$0")/.." && pwd)
awk -v pat='${AUTHORIZED_KEYS_FILE:-${HOME}/.ssh/authorized_keys}' -v fixed='/root/.ssh/authorized_keys' '
    NR == 1 {
        print "# Generated by tools/coolify-compose.sh from compose.yml: do not edit."
        print "# For Coolify, which refuses a variable in a volume source: the file of keys is the host'"'"'s"
        print "# /root/.ssh/authorized_keys. Set AUTHORIZED_KEYS_FILE to another path in compose.yml, not here."
    }
    { i = index($0, pat); if (i) $0 = substr($0, 1, i - 1) fixed substr($0, i + length(pat)); print }
' "$ROOT/compose.yml"
