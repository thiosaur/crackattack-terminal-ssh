#!/bin/sh
# Writes compose.coolify.yml on stdout, from compose.yml.
#
# Coolify refuses a variable (${...}) in the source of a volume. In the Coolify version the
# players' directory is a named volume bound to KEYS_DIR (a variable in `device:`, which Coolify
# does not check), and the one-shot import is left out. In compose.yml, lines between
# `#--local-only` and `#--end-local-only` are dropped, and `#--coolify: ` is removed from the
# start of the lines that carry it.
#
#   tools/coolify-compose.sh > compose.coolify.yml
set -eu

ROOT=$(cd "$(dirname "$0")/.." && pwd)
awk '
    NR == 1 {
        print "# Generated by tools/coolify-compose.sh from compose.yml: do not edit."
        print "# For Coolify: set KEYS_DIR to the directory of the players keys, on the server (it must exist)."
    }
    !started && /^services:/ { started = 1 }
    !started { next }
    /^[ \t]*#--end-local-only/ { skip = 0; next }
    /^[ \t]*#--local-only/ { skip = 1; next }
    skip { next }
    { i = index($0, "#--coolify: "); if (i) $0 = substr($0, 1, i - 1) substr($0, i + 12); print }
' "$ROOT/compose.yml"
